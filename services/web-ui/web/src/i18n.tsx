const DICTS: Record<Lang, Record<MsgKey, Msg>> = { en, ru };

// Language self-names are never translated. The Russian one ("Russkiy" in Cyrillic) is built from code
// points so that the only Cyrillic in source code lives in the `ru` dictionary.
export const LANG_NAMES: Record<Lang, string> = {
  en: "English",
  ru: String.fromCharCode(0x420, 0x443, 0x441, 0x441, 0x43a, 0x438, 0x439),
};

// ── Preference and active language ─────────────────────────────────────

const LANG_KEY = "kn.lang";

function readPref(): LangPref {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v === "en" || v === "ru" || v === "system") return v;
  } catch {
    /* storage unavailable: fall back to the system language */
  }
  return "system";
}

function writePref(p: LangPref) {
  try {
    if (p === "system") localStorage.removeItem(LANG_KEY);
    else localStorage.setItem(LANG_KEY, p);
  } catch {
    /* private mode: the choice just is not remembered */
  }
}

export function systemLang(): Lang {
  const nav = typeof navigator !== "undefined" ? navigator.language || "" : "";
  return nav.toLowerCase().startsWith("ru") ? "ru" : "en";
}

export const resolveLang = (p: LangPref): Lang => (p === "system" ? systemLang() : p);

// The active language is also kept at module level so plain helpers (fmtDate, translate) outside
// React components follow the UI language. The provider updates it before its children render.
let activeLang: Lang = resolveLang(readPref());
const applyLang = (l: Lang) => {
  activeLang = l;
  if (typeof document !== "undefined") document.documentElement.lang = l;
};
applyLang(activeLang);

/** Current UI language, for code outside React components. Inside components prefer useT().lang. */
export const getLang = (): Lang => activeLang;

export function hasMsg(key: string): key is MsgKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}

const pluralRules = new Map<Lang, Intl.PluralRules>();
function pickPlural(m: Plural, count: number, lang: Lang): string {
  let pr = pluralRules.get(lang);
  if (!pr) pluralRules.set(lang, (pr = new Intl.PluralRules(lang)));
  const cat = pr.select(count) as keyof Plural;
  return m[cat] ?? m.other ?? m.many ?? m.one;
}

function resolveMsg(key: MsgKey, params: Params | undefined, lang: Lang): string {
  const m = DICTS[lang][key] ?? en[key];
  if (typeof m === "string") return m;
  return pickPlural(m, Number(params?.count ?? 0), lang);
}

/** Translate outside React (or with an explicit language). `{name}` placeholders are filled from params. */
export function translate(key: MsgKey, params?: Params, lang: Lang = activeLang): string {
  const s = resolveMsg(key, params, lang);
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (all, name: string) => (name in params ? String(params[name]) : all));
}

/** Like translate, but placeholders may be React nodes (links, <code>, <strong>…). */
export function translateRich(key: MsgKey, params: Record<string, ReactNode>, lang: Lang = activeLang): ReactNode {
  const count = typeof params.count === "number" ? params.count : undefined;
  const s = resolveMsg(key, count === undefined ? undefined : { count }, lang);
  const parts = s.split(/\{(\w+)\}/g);
  return parts.map((p, i) => (i % 2 === 1 ? <Fragment key={i}>{p in params ? params[p] : `{${p}}`}</Fragment> : p));
}

// ── Locale-aware formatting ────────────────────────────────────────────

const LOCALE: Record<Lang, string> = { en: "en-US", ru: "ru-RU" };

export function formatDate(value: string | number | Date, opts: Intl.DateTimeFormatOptions = { dateStyle: "medium" }, lang: Lang = activeLang) {
  return new Intl.DateTimeFormat(LOCALE[lang], opts).format(value instanceof Date ? value : new Date(value));
}

export function formatNumber(n: number, opts?: Intl.NumberFormatOptions, lang: Lang = activeLang) {
  return new Intl.NumberFormat(LOCALE[lang], opts).format(n);
}

// ── React ──────────────────────────────────────────────────────────────

export type TFunc = (key: MsgKey, params?: Params) => string;

export interface I18n {
  /** Translate a key; `{name}` placeholders come from params, plural messages use params.count. */
  t: TFunc;
  /** Translate with React nodes as placeholder values. */
  rich: (key: MsgKey, params: Record<string, ReactNode>) => ReactNode;
  /** Active (resolved) language. */
  lang: Lang;
  /** Stored preference: "system" | "en" | "ru". */
  pref: LangPref;
  setLang: (p: LangPref) => void;
  fmtDate: (value: string | number | Date, opts?: Intl.DateTimeFormatOptions) => string;
  fmtNumber: (n: number, opts?: Intl.NumberFormatOptions) => string;
}

const I18nCtx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [pref, setPref] = useState<LangPref>(readPref);
  const lang = resolveLang(pref);
  if (activeLang !== lang) applyLang(lang); // synchronously, so plain helpers in children see it

  const setLang = useCallback((p: LangPref) => {
    writePref(p);
    setPref(p);
  }, []);

  const value = useMemo<I18n>(() => ({
    t: (key, params) => translate(key, params, lang),
    rich: (key, params) => translateRich(key, params, lang),
    lang,
    pref,
    setLang,
    fmtDate: (v, opts) => formatDate(v, opts, lang),
    fmtNumber: (n, opts) => formatNumber(n, opts, lang),
  }), [lang, pref, setLang]);

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useT(): I18n {
  const v = useContext(I18nCtx);
  if (!v) throw new Error("useT() must be used inside <I18nProvider>");
  return v;
}
